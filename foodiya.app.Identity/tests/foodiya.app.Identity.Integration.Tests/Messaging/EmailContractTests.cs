[TestClass]
public sealed class EmailContractTests(TestContext testContext)
{
    [TestMethod]
    [DataRow(150, true)]
    [DataRow(151, true)]
    [DataRow(256, true)]
    [DataRow(257, false)]
    public async Task RegistrationAndProfileConsumer_AgreeOnEmailLength(int length, bool accepted)
    {
        var email = Email(length);
        var request = new RegisterRequest
        { Email = email, UserName = "boundary.user", Password = "Valid!Password123", FirstName = "Boundary", LastName = "User" };
        Assert.AreEqual(accepted, Validator.TryValidateObject(request, new ValidationContext(request), [], true));
        await using var database = new ProfileTestDatabase();
        await database.InitializeAsync(testContext.CancellationToken);
        await using var db = database.CreateContext();
        var handler = new IdentityProfileEventHandler(db, new IdentityProfileProvisioner(db, TimeProvider.System));
        var envelope = new IntegrationEventEnvelope(Guid.NewGuid(), "UserRegistered", DateTimeOffset.UtcNow,
            JsonSerializer.SerializeToElement(new UserRegisteredEventPayload(Guid.NewGuid(), email)));
        if (accepted)
        {
            await handler.HandleAsync(envelope, testContext.CancellationToken);
            Assert.AreEqual(email, (await db.AppUsers.SingleAsync(testContext.CancellationToken)).Email);
        }
        else
        {
            await Assert.ThrowsExactlyAsync<JsonException>(() => handler.HandleAsync(envelope, testContext.CancellationToken));
            Assert.AreEqual(0, await db.AppUsers.CountAsync(testContext.CancellationToken));
        }
    }

    [TestMethod]
    [DataRow(false)]
    [DataRow(true)]
    [TestCategory("SqlServer")]
    [Timeout(60000, CooperativeCancellation = true)]
    public async Task EmailMigration_ExpandsExistingColumnAndStoresFull256Characters(bool uniqueConstraint)
    {
        var ct = testContext.CancellationToken;
        await using var database = await SqlServerTestDatabase.CreateAsync(ct);
        await using var db = new AutoGeneratedDbContext(database.ProfileOptions);
        await db.Database.EnsureCreatedAsync(ct);
        await db.Database.ExecuteSqlRawAsync("DROP INDEX UQ_AppUser_Email ON dbo.AppUser; ALTER TABLE dbo.AppUser ALTER COLUMN Email varchar(150) NOT NULL;", ct);
        await db.Database.ExecuteSqlRawAsync(uniqueConstraint
            ? "ALTER TABLE dbo.AppUser ADD CONSTRAINT UQ_AppUser_Email UNIQUE NONCLUSTERED (Email);"
            : "CREATE UNIQUE NONCLUSTERED INDEX UQ_AppUser_Email ON dbo.AppUser (Email);", ct);
        await db.Database.ExecuteSqlRawAsync("ALTER TABLE dbo.AppUser ALTER COLUMN FirstName varchar(100) NOT NULL; ALTER TABLE dbo.AppUser ALTER COLUMN LastName varchar(100) NOT NULL;", ct);
        await Assert.ThrowsExactlyAsync<InvalidOperationException>(() => IdentityProjectionDatabase.EnsureAvailableAsync(db, ct));
        var migration = await File.ReadAllTextAsync(Path.Combine(AppContext.BaseDirectory, "Sql", "Migration_AppUserEmail256.sql"), ct);
        await db.Database.ExecuteSqlRawAsync(migration, ct);
        await db.Database.ExecuteSqlRawAsync(migration, ct);
        var namesMigration = await File.ReadAllTextAsync(Path.Combine(AppContext.BaseDirectory, "Sql", "Migration_IdentityProfileUnicodeNames.sql"), ct);
        await db.Database.ExecuteSqlRawAsync(namesMigration, ct);
        await db.Database.ExecuteSqlRawAsync(namesMigration, ct);
        await IdentityProjectionDatabase.EnsureAvailableAsync(db, ct);
        var email = Email(256);
        var profile = await new IdentityProfileProvisioner(db, TimeProvider.System)
            .EnsureAsync(new UserRegisteredEventPayload(Guid.NewGuid(), email), null, ct);
        await db.SaveChangesAsync(ct);
        db.ChangeTracker.Clear();
        Assert.AreEqual(email, (await db.AppUsers.SingleAsync(user => user.Uuid == profile.Uuid, ct)).Email);
        var unicodeEmail = "料理@exemple.test";
        await new IdentityProfileProvisioner(db, TimeProvider.System)
            .EnsureAsync(new UserRegisteredEventPayload(Guid.NewGuid(), unicodeEmail, FirstName: "Juan Carlos", LastName: "العلمي"), null, ct);
        await db.SaveChangesAsync(ct);
        db.ChangeTracker.Clear();
        var unicodeProfile = await db.AppUsers.SingleAsync(user => user.Email == unicodeEmail, ct);
        Assert.AreEqual(unicodeEmail, unicodeProfile.Email);
        Assert.AreEqual("Juan Carlos", unicodeProfile.FirstName);
        Assert.AreEqual("العلمي", unicodeProfile.LastName);
        db.AppUsers.Add(new AppUser
        {
            Uuid = Guid.NewGuid(), Email = email, UserName = "unique.check", FirstName = "Unique", LastName = "Check",
            PasswordHash = [], PasswordSalt = [], Role = "USER", IsActive = true, DeleteReason = string.Empty,
            Code = EntityCodeGenerator.For("USR"), DateInsert = DateTime.UtcNow
        });
        var duplicate = await Assert.ThrowsExactlyAsync<DbUpdateException>(() => db.SaveChangesAsync(ct));
        Assert.IsNotNull(duplicate.InnerException);
        Assert.Contains("UQ_AppUser_Email", duplicate.InnerException.Message, StringComparison.Ordinal);
    }

    private static string Email(int length)
    {
        const int localLength = 64;
        var domainLength = length - localLength - 1;
        var labels = (domainLength + 64) / 64;
        var letters = domainLength - labels + 1;
        return new string('u', localLength) + "@" + string.Join('.', Enumerable.Range(0, labels)
            .Select(index => new string('d', letters / labels + (index < letters % labels ? 1 : 0))));
    }
}
