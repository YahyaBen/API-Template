using Foodiya.Infrastructure.Data;
using Foodiya.Infrastructure.Identity;
using Microsoft.Data.Sqlite;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.Extensions.DependencyInjection;

namespace foodiya.app.Identity.Integration.Tests.Messaging;

internal sealed class ProfileTestDatabase : IAsyncDisposable
{
    public SqliteConnection Connection { get; } = new($"Data Source=profiles-{Guid.NewGuid():N};Mode=Memory;Cache=Shared;Pooling=false;Default Timeout=1");
    public DbContextOptions<AutoGeneratedDbContext> Options => new DbContextOptionsBuilder<AutoGeneratedDbContext>()
        .UseSqlite(Connection.ConnectionString).ReplaceService<IModelCustomizer, ProfileSqliteModelCustomizer>().Options;

    public async Task InitializeAsync(CancellationToken cancellationToken)
    {
        await Connection.OpenAsync(cancellationToken);
        await using var db = CreateContext();
        await db.Database.EnsureCreatedAsync(cancellationToken);
    }
    public AutoGeneratedDbContext CreateContext() => new(Options);
    public void Register(IServiceCollection services)
    {
        services.AddScoped(_ => CreateContext());
        services.AddSingleton(TimeProvider.System);
        services.AddScoped<IdentityProfileProvisioner>();
    }
    public ValueTask DisposeAsync() => Connection.DisposeAsync();
}

internal sealed class ProfileSqliteModelCustomizer(ModelCustomizerDependencies dependencies)
    : ModelCustomizer(dependencies)
{
    public override void Customize(ModelBuilder modelBuilder, DbContext context)
    {
        base.Customize(modelBuilder, context);
        // Exercise real relational constraints and transactions without SQL
        // Server's generated default expressions and provider-specific types.
        foreach (var entity in modelBuilder.Model.GetEntityTypes())
        foreach (var property in entity.GetProperties())
        {
            property.SetDefaultValueSql(null);
            property.SetColumnType(null);
        }
    }
}
