using Foodiya.Infrastructure.Data;
using foodiya.app.Identity.Infrastructure.Persistence;
using Microsoft.Data.SqlClient;
using Microsoft.EntityFrameworkCore;

namespace foodiya.app.Identity.Integration.Tests.TestSupport;

internal sealed class SqlServerTestDatabase(string connectionString) : IAsyncDisposable
{
    public DbContextOptions<IdentityDataContext> IdentityOptions => new DbContextOptionsBuilder<IdentityDataContext>().UseSqlServer(connectionString).Options;
    public DbContextOptions<AutoGeneratedDbContext> ProfileOptions => new DbContextOptionsBuilder<AutoGeneratedDbContext>().UseSqlServer(connectionString).Options;

    public static Task<SqlServerTestDatabase> CreateAsync(CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();
        var configured = Environment.GetEnvironmentVariable("SQLSERVER_TEST_CONNECTION");
        if (string.IsNullOrWhiteSpace(configured))
            Assert.Inconclusive("Set SQLSERVER_TEST_CONNECTION or run scripts/Test-SqlServer.ps1 to execute SQL Server tests.");
        var builder = new SqlConnectionStringBuilder(configured)
        {
            InitialCatalog = $"foodiya_tests_{Guid.NewGuid():N}", Pooling = false
        };
        var database = new SqlServerTestDatabase(builder.ConnectionString);
        // EnsureCreated creates only a database owned by this test. The supplied
        // connection's catalog is always replaced with a generated test name.
        return Task.FromResult(database);
    }

    public async ValueTask DisposeAsync()
    {
        var name = new SqlConnectionStringBuilder(connectionString).InitialCatalog;
        if (!name.StartsWith("foodiya_tests_", StringComparison.Ordinal))
            throw new InvalidOperationException("Refusing to remove a database outside the test namespace.");
        await using var db = new IdentityDataContext(IdentityOptions);
        await db.Database.EnsureDeletedAsync(CancellationToken.None);
    }
}
