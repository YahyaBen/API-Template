using Foodiya.Domain.Constants;
using Foodiya.Domain.Exceptions;
using Foodiya.Domain.Extensions;
using Foodiya.Domain.Models;
using Foodiya.Infrastructure.Data;
using foodiya.app.Messaging;
using Microsoft.EntityFrameworkCore;

namespace Foodiya.Infrastructure.Identity;

/// <summary>Creates profiles by immutable Identity subject. Callers own the transaction and save.</summary>
public sealed class IdentityProfileProvisioner(AutoGeneratedDbContext db, TimeProvider clock)
{
    public async Task<AppUser> EnsureAsync(UserRegisteredEventPayload identity,
        IReadOnlyCollection<string>? roles, CancellationToken cancellationToken)
    {
        var email = identity.Email?.Trim().ToLowerInvariant();
        if (identity.Id == Guid.Empty || string.IsNullOrWhiteSpace(email) || email.Length > 256)
            throw new ArgumentException("Invalid identity subject or email.");

        var profile = await db.AppUsers.SingleOrDefaultAsync(user => user.Uuid == identity.Id, cancellationToken);
        if (profile is not null)
        {
            // Registration events preserve edits. Authenticated requests may refresh
            // roles, but never reactivate a deleted profile or change its subject.
            if (profile.IsActive && roles is not null && profile.Role != GetPrimaryRole(roles))
            {
                profile.Role = GetPrimaryRole(roles);
                profile.DateModif = clock.GetUtcNow().UtcDateTime;
            }
            return profile;
        }

        if (await db.AppUsers.AnyAsync(user => user.Email == email, cancellationToken))
            throw new FoodiyaValueAlreadyExistsException("Email is already linked to a different Foodiya profile.");

        profile = new AppUser
        {
            Uuid = identity.Id,
            Email = email,
            UserName = Trim(identity.UserName, $"identity_{identity.Id:N}", 50),
            FirstName = Trim(identity.FirstName, "Foodiya", 100),
            LastName = Trim(identity.LastName, string.Empty, 100),
            PasswordHash = [], PasswordSalt = [],
            Role = GetPrimaryRole(roles ?? []),
            IsActive = true,
            DeleteReason = string.Empty,
            Code = EntityCodeGenerator.For("USR"),
            DateInsert = clock.GetUtcNow().UtcDateTime
        };
        db.AppUsers.Add(profile);
        return profile;
    }

    private static string GetPrimaryRole(IReadOnlyCollection<string> roles)
    {
        if (roles.Contains(AppRoleConstants.SuperAdmin)) return AppRoleConstants.SuperAdmin;
        if (roles.Contains(AppRoleConstants.Admin)) return AppRoleConstants.Admin;
        if (roles.Contains(AppRoleConstants.Chef)) return AppRoleConstants.Chef;
        return AppRoleConstants.User;
    }

    private static string Trim(string? value, string fallback, int maxLength)
    {
        var normalized = string.IsNullOrWhiteSpace(value) ? fallback : value.Trim();
        return normalized[..Math.Min(normalized.Length, maxLength)];
    }
}
