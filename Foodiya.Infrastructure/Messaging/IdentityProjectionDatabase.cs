using Foodiya.Infrastructure.Data;
using Microsoft.EntityFrameworkCore;

namespace Foodiya.Infrastructure.Messaging;

public static class IdentityProjectionDatabase
{
    public static async Task EnsureAvailableAsync(AutoGeneratedDbContext db, CancellationToken cancellationToken)
    {
        using var deadline = CancellationTokenSource.CreateLinkedTokenSource(cancellationToken);
        deadline.CancelAfter(TimeSpan.FromSeconds(10));
        cancellationToken = deadline.Token;
        // CanConnect alone reports healthy when the inbox migration is missing.
        _ = await db.AppUsers.AsNoTracking().Take(1).ToArrayAsync(cancellationToken);
        _ = await db.IdentityInboxMessages.AsNoTracking().Take(1).ToArrayAsync(cancellationToken);
        if (db.Database.IsSqlServer())
        {
            var readyColumns = await db.Database.SqlQueryRaw<int>(
                "SELECT COUNT(*) AS [Value] FROM INFORMATION_SCHEMA.COLUMNS "
                + "WHERE TABLE_SCHEMA = N'dbo' AND TABLE_NAME = N'AppUser' AND COLUMN_NAME IN (N'Email', N'FirstName', N'LastName') "
                + "AND DATA_TYPE = N'nvarchar' AND (CHARACTER_MAXIMUM_LENGTH = -1 "
                + "OR CHARACTER_MAXIMUM_LENGTH >= CASE WHEN COLUMN_NAME = N'Email' THEN 256 ELSE 100 END)")
                .SingleAsync(cancellationToken);
            if (readyColumns != 3)
                throw new InvalidOperationException("Apply the Identity profile email and Unicode-name migrations before consuming events.");
        }
    }
}
