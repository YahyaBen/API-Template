using System.Data;
using System.IdentityModel.Tokens.Jwt;
using Foodiya.Domain.Exceptions;
using Foodiya.Infrastructure.Data;
using Foodiya.Infrastructure.Identity;
using foodiya.app.Messaging;
using Microsoft.EntityFrameworkCore;

namespace Foodiya.API.Middleware;

internal sealed class IdentityProfileProvisioningMiddleware(RequestDelegate next)
{
    public async Task InvokeAsync(HttpContext context, AutoGeneratedDbContext db, IdentityProfileProvisioner profiles)
    {
        if (context.User.Identity?.IsAuthenticated == true
            && Guid.TryParse(context.User.FindFirst(JwtRegisteredClaimNames.Sub)?.Value, out var subject))
        {
            var email = context.User.FindFirst(JwtRegisteredClaimNames.Email)?.Value;
            if (string.IsNullOrWhiteSpace(email))
                throw new FoodiyaForbiddenException("The Identity token must contain an email address.");

            var name = (context.User.FindFirst("name")?.Value ?? string.Empty)
                .Split(' ', 2, StringSplitOptions.RemoveEmptyEntries);
            var identity = new UserRegisteredEventPayload(subject, email,
                context.User.FindFirst("preferred_username")?.Value,
                context.User.FindFirst(JwtRegisteredClaimNames.GivenName)?.Value ?? name.ElementAtOrDefault(0),
                context.User.FindFirst(JwtRegisteredClaimNames.FamilyName)?.Value ?? name.ElementAtOrDefault(1));
            var roles = context.User.FindAll("role").Select(claim => claim.Value).ToArray();

            await db.Database.CreateExecutionStrategy().ExecuteAsync(async () =>
            {
                db.ChangeTracker.Clear();
                await using var transaction = await db.Database.BeginTransactionAsync(IsolationLevel.Serializable, context.RequestAborted);
                var profile = await profiles.EnsureAsync(identity, roles, context.RequestAborted);
                if (!profile.IsActive)
                    throw new FoodiyaForbiddenException("The Foodiya profile is inactive.");
                await db.SaveChangesAsync(context.RequestAborted);
                await transaction.CommitAsync(context.RequestAborted);
            });
        }
        await next(context);
    }
}
