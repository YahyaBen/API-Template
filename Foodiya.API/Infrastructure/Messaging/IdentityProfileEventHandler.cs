using System.Data;
using System.Text.Json;
using Foodiya.Domain.Exceptions;
using Foodiya.Domain.Models;
using Foodiya.Infrastructure.Data;
using Foodiya.Infrastructure.Identity;
using foodiya.app.Messaging;
using Microsoft.EntityFrameworkCore;

namespace Foodiya.Infrastructure.Messaging;

public sealed class IdentityProfileEventHandler(AutoGeneratedDbContext db, IdentityProfileProvisioner profiles)
{
    public async Task HandleAsync(IntegrationEventEnvelope envelope, CancellationToken cancellationToken)
    {
        if (envelope.Id == Guid.Empty || envelope.SchemaVersion != 1 || envelope.Source != "foodiya.app.Identity")
            throw new JsonException("Unsupported Identity event envelope.");
        if (envelope.Type != "UserRegistered") return;
        if (envelope.Payload.ValueKind != JsonValueKind.Object)
            throw new JsonException("Invalid registration payload.");
        var payload = envelope.Payload.Deserialize<UserRegisteredEventPayload>(IntegrationEventEnvelope.JsonOptions)
            ?? throw new JsonException("Missing registration payload.");
        if (payload.Id == Guid.Empty || string.IsNullOrWhiteSpace(payload.Email) || payload.Email.Length > 256)
            throw new JsonException("Invalid identity subject or email.");

        // SQL Server execution strategies require the whole explicit transaction
        // to be retried as a unit. Inbox and profile commit together.
        await db.Database.CreateExecutionStrategy().ExecuteAsync(async () =>
        {
            db.ChangeTracker.Clear();
            await using var transaction = await db.Database.BeginTransactionAsync(IsolationLevel.Serializable, cancellationToken);
            if (await db.IdentityInboxMessages.AnyAsync(message => message.EventId == envelope.Id, cancellationToken))
            {
                await transaction.CommitAsync(cancellationToken);
                return;
            }

            try
            {
                await profiles.EnsureAsync(payload, roles: null, cancellationToken);
            }
            catch (FoodiyaValueAlreadyExistsException exception)
            {
                throw new JsonException(exception.Message, exception);
            }
            db.IdentityInboxMessages.Add(new IdentityInboxMessage
            {
                EventId = envelope.Id,
                EventType = envelope.Type,
                ProcessedAtUtc = DateTime.UtcNow
            });
            await db.SaveChangesAsync(cancellationToken);
            await transaction.CommitAsync(cancellationToken);
        });
    }
}
