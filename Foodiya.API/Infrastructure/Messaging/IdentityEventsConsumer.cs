using System.Diagnostics;
using System.Text;
using System.Text.Json;
using foodiya.app.Messaging;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using RabbitMQ.Client;
using RabbitMQ.Client.Events;
using Foodiya.Infrastructure.Data;

namespace Foodiya.Infrastructure.Messaging;

public sealed class IdentityEventsConsumer(IServiceScopeFactory scopeFactory,
    IOptions<RabbitMqOptions> rabbitOptions, IOptions<IdentityEventsOptions> consumerOptions,
    ILogger<IdentityEventsConsumer> logger) : BackgroundService
{
    private volatile bool _connected;
    public bool IsConnected => _connected;

    protected override async Task ExecuteAsync(CancellationToken stoppingToken)
    {
        while (!stoppingToken.IsCancellationRequested)
        {
            try
            {
                var factory = RabbitMqConnectionFactory.Create(rabbitOptions.Value, "Foodiya profile consumer");
                // This loop handles both initial failures and lost connections,
                // redeclaring topology before registering a replacement consumer.
                factory.AutomaticRecoveryEnabled = false;
                await using var connection = await factory.CreateConnectionAsync(stoppingToken);
                await using var channel = await connection.CreateChannelAsync(cancellationToken: stoppingToken);
                var disconnected = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
                channel.ChannelShutdownAsync += (_, _) => { disconnected.TrySetResult(); return Task.CompletedTask; };
                await RabbitMqTopology.DeclareAsync(channel, rabbitOptions.Value.Exchange,
                    consumerOptions.Value.Queue, consumerOptions.Value.MaxAttempts, stoppingToken);
                await EnsureDatabaseAvailableAsync(stoppingToken);
                await channel.BasicQosAsync(0, 1, false, stoppingToken);
                var consumer = new AsyncEventingBasicConsumer(channel);
                consumer.ReceivedAsync += (_, delivery) => ProcessAsync(channel, delivery, disconnected, stoppingToken);
                await channel.BasicConsumeAsync(consumerOptions.Value.Queue, autoAck: false, consumer: consumer,
                    cancellationToken: stoppingToken);
                _connected = true;
                logger.LogInformation("Identity event consumer connected to queue {Queue}.", consumerOptions.Value.Queue);
                while (!disconnected.Task.IsCompleted)
                {
                    await Task.WhenAny(disconnected.Task, Task.Delay(TimeSpan.FromSeconds(consumerOptions.Value.RetryDelaySeconds), stoppingToken));
                    stoppingToken.ThrowIfCancellationRequested();
                    if (!disconnected.Task.IsCompleted) await EnsureDatabaseAvailableAsync(stoppingToken);
                }
            }
            catch (OperationCanceledException) when (stoppingToken.IsCancellationRequested) { break; }
            catch (Exception exception)
            {
                logger.LogWarning(exception, "Identity event consumer connection failed; retrying.");
            }
            finally { _connected = false; }

            try { await Task.Delay(TimeSpan.FromSeconds(consumerOptions.Value.RetryDelaySeconds), stoppingToken); }
            catch (OperationCanceledException) when (stoppingToken.IsCancellationRequested) { break; }
        }
    }

    private async Task EnsureDatabaseAvailableAsync(CancellationToken cancellationToken)
    {
        await using var scope = scopeFactory.CreateAsyncScope();
        await IdentityProjectionDatabase.EnsureAvailableAsync(scope.ServiceProvider.GetRequiredService<AutoGeneratedDbContext>(), cancellationToken);
    }

    private async Task ProcessAsync(IChannel channel, BasicDeliverEventArgs delivery,
        TaskCompletionSource restart, CancellationToken stoppingToken)
    {
        try
        {
            // Deserialize while the callback owns RabbitMQ.Client's body memory.
            var envelope = JsonSerializer.Deserialize<IntegrationEventEnvelope>(delivery.Body.Span,
                IntegrationEventEnvelope.JsonOptions) ?? throw new JsonException("Missing Identity event.");
            var traceParent = delivery.BasicProperties.Headers?.TryGetValue("traceparent", out var trace) == true
                ? trace as string ?? (trace is byte[] bytes ? Encoding.UTF8.GetString(bytes) : null) : null;
            using var activity = RabbitMqPublisher.Activities.StartActivity("rabbitmq.consume", ActivityKind.Consumer,
                ActivityContext.TryParse(traceParent, null, out var parent) ? parent : default);
            await using var scope = scopeFactory.CreateAsyncScope();
            await scope.ServiceProvider.GetRequiredService<IdentityProfileEventHandler>().HandleAsync(envelope, stoppingToken);
            await channel.BasicAckAsync(delivery.DeliveryTag, multiple: false, cancellationToken: stoppingToken);
            logger.LogInformation("Processed Identity event {EventId} ({EventType}).", envelope.Id, envelope.Type);
        }
        catch (OperationCanceledException) when (stoppingToken.IsCancellationRequested) { }
        catch (JsonException exception)
        {
            logger.LogWarning(exception, "Invalid Identity event {MessageId}; dead-lettering.", delivery.BasicProperties.MessageId);
            await channel.BasicRejectAsync(delivery.DeliveryTag, requeue: false, cancellationToken: stoppingToken);
        }
        catch (Exception exception)
        {
            try { await EnsureDatabaseAvailableAsync(stoppingToken); }
            catch (OperationCanceledException) when (stoppingToken.IsCancellationRequested) { return; }
            catch (Exception databaseFailure)
            {
                _connected = false;
                logger.LogWarning(databaseFailure, "Pausing Identity events until the projection database is available.");
                // Leave this delivery unacknowledged. The outer loop closes the
                // channel and checks the database before starting a consumer.
                restart.TrySetResult();
                return;
            }
            var failures = delivery.BasicProperties.Headers?.TryGetValue("x-delivery-count", out var count) == true
                ? Convert.ToInt64(count) : 0;
            var retry = failures + 1 < consumerOptions.Value.MaxAttempts;
            logger.LogWarning(exception, "Identity event {MessageId} failed; retry={Retry}.", delivery.BasicProperties.MessageId, retry);
            if (retry) await Task.Delay(TimeSpan.FromSeconds(consumerOptions.Value.RetryDelaySeconds), stoppingToken);
            // RabbitMQ 4.3 increments its failure counter for basic.reject,
            // while basic.nack no longer counts towards the delivery limit.
            await channel.BasicRejectAsync(delivery.DeliveryTag, requeue: retry, cancellationToken: stoppingToken);
        }
    }
}
