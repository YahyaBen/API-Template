using Foodiya.Infrastructure.Data;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Diagnostics.HealthChecks;

namespace Foodiya.Infrastructure.Messaging;

public sealed class IdentityConsumerHealthCheck(IdentityEventsConsumer consumer, IServiceScopeFactory scopes) : IHealthCheck
{
    public async Task<HealthCheckResult> CheckHealthAsync(HealthCheckContext context, CancellationToken cancellationToken = default)
    {
        if (!consumer.IsConnected)
            return HealthCheckResult.Unhealthy("Identity event consumer is not ready.");
        try
        {
            await using var scope = scopes.CreateAsyncScope();
            await IdentityProjectionDatabase.EnsureAvailableAsync(scope.ServiceProvider.GetRequiredService<AutoGeneratedDbContext>(), cancellationToken);
            return HealthCheckResult.Healthy();
        }
        catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested) { throw; }
        catch (Exception exception)
        {
            return HealthCheckResult.Unhealthy("Identity projection database or schema is unavailable.", exception);
        }
    }
}
