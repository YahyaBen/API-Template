using Foodiya.Application.Interfaces.Services;
using Foodiya.Domain.Exceptions;
using Foodiya.Domain.Models;
using Foodiya.Domain.Constants;
using Foodiya.Domain.Specifications;
using Foodiya.Infrastructure.Data;
using Microsoft.EntityFrameworkCore;

namespace Foodiya.Infrastructure.Identity;

internal sealed class ResourceAuthorization(AutoGeneratedDbContext db, ICurrentUser user) : IResourceAuthorization
{
    private int? _actorId;

    public async Task<int> GetActorIdAsync(Guid suppliedUserUuid, CancellationToken ct)
    {
        var subject = user.UserUuid;
        if (suppliedUserUuid != Guid.Empty && suppliedUserUuid != subject)
            throw new FoodiyaForbiddenException("The acting user must match the authenticated Identity subject.");

        return _actorId ??= await db.AppUsers.AsNoTracking()
            .Where(profile => profile.Uuid == subject && profile.IsActive && profile.DeletedAt == null)
            .Select(profile => (int?)profile.Id).SingleOrDefaultAsync(ct)
            ?? throw new FoodiyaForbiddenException("An active Foodiya profile is required.");
    }

    public async Task RequireChefOwnerAsync(int chefId, CancellationToken ct)
    {
        var actorId = await GetActorIdAsync(Guid.Empty, ct);
        var ownerId = await db.ChefProfiles.AsNoTracking()
            .Where(chef => chef.Id == chefId && chef.DeletedAt == null)
            .Select(chef => (int?)chef.UserId).SingleOrDefaultAsync(ct)
            ?? throw new FoodiyaNotFoundException("The chef profile was not found.");
        if (!user.IsAdministrator && ownerId != actorId)
            throw new FoodiyaForbiddenException("Only the owner or an administrator can change this chef's content.");
    }

    public async Task RequireRecipeOwnerAsync(int recipeId, CancellationToken ct)
    {
        var chefId = await db.Recipes.AsNoTracking()
            .Where(recipe => recipe.Id == recipeId && recipe.DeletedAt == null)
            .Select(recipe => (int?)recipe.ChefId).SingleOrDefaultAsync(ct)
            ?? throw new FoodiyaNotFoundException("The recipe was not found.");
        await RequireChefOwnerAsync(chefId, ct);
    }

    public async Task RequireShareOwnerAsync(RecipeShare share, CancellationToken ct)
    {
        var actorId = await GetActorIdAsync(Guid.Empty, ct);
        if (!user.IsAdministrator && share.SharedByUserId != actorId)
            throw new FoodiyaForbiddenException("Only the sender or an administrator can change this share.");
    }

    public async Task<RecipeReadAccess> GetReadAccessAsync(CancellationToken ct) =>
        new(await GetActorIdAsync(Guid.Empty, ct), user.IsAdministrator);

    public async Task RequireRecipeReadAsync(int recipeId, CancellationToken ct)
    {
        var access = await GetReadAccessAsync(ct);
        if (!await db.Recipes.AsNoTracking().Where(access.Recipes(allowUnlisted: true))
                .AnyAsync(recipe => recipe.Id == recipeId, ct))
            throw new FoodiyaNotFoundException("The recipe was not found.");
    }

    public async Task RequireRecipeShareAsync(int recipeId, CancellationToken ct)
    {
        await RequireRecipeReadAsync(recipeId, ct);
        var actorId = await GetActorIdAsync(Guid.Empty, ct);
        if (!user.IsAdministrator && await db.Recipes.AnyAsync(recipe => recipe.Id == recipeId
                && recipe.Visibility == RecipeVisibilityConstants.Private && recipe.Chef.UserId != actorId, ct))
            throw new FoodiyaForbiddenException("Only the owner or an administrator can share a private recipe.");
    }

    public async Task RequireShareReadAsync(RecipeShare share, CancellationToken ct)
    {
        var actorId = await GetActorIdAsync(Guid.Empty, ct);
        if (!user.IsAdministrator && share.SharedByUserId != actorId && share.SharedWithUserId != actorId)
            throw new FoodiyaNotFoundException("The share was not found.");
        await RequireRecipeReadAsync(share.RecipeId, ct);
    }
}
